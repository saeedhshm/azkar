/// Design Tokens — Spacing System
/// استخدم هذه القيم دائماً بدلاً من الأرقام الثابتة
class AppSpacing {
  AppSpacing._();

  /// 4px — مسافة صغيرة جداً (بين الأيقونة والنص)
  static const double xs = 4;

  /// 8px — مسافة صغيرة (بين العناصر المتقاربة)
  static const double sm = 8;

  /// 12px — مسافة متوسطة صغيرة
  static const double md = 12;

  /// 16px — مسافة متوسطة (padding افتراضي)
  static const double lg = 16;

  /// 20px — مسافة متوسطة كبيرة
  static const double xl = 20;

  /// 24px — مسافة كبيرة (بين الأقسام)
  static const double xxl = 24;

  /// 32px — مسافة كبيرة جداً
  static const double xxxl = 32;

  /// 48px — مسافة ضخمة (spacing بين الأقسام الرئيسية)
  static const double huge = 48;

  /// Padding افتراضي للـ Page
  static const double pagePadding = 16;

  /// Padding للـ Cards
  static const double cardPadding = 16;

  /// Padding للـ Bottom Sheets
  static const double sheetPadding = 20;
}
